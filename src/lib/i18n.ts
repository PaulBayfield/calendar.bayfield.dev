export type Lang = "en" | "fr";
export type Translate = (key: StringKey, vars?: Record<string, string | number>) => string;

export function resolveLang(setting: "auto" | Lang): Lang {
  if (setting !== "auto") return setting;
  return navigator.language.toLowerCase().startsWith("fr") ? "fr" : "en";
}

export function makeT(lang: Lang): Translate {
  const strings = lang === "fr" ? fr : en;
  return (key, vars) =>
    strings[key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? `{${name}}`));
}

export type Formats = ReturnType<typeof makeFormats>;

export function makeFormats(lang: Lang, timeFormat: "auto" | "24h" | "12h") {
  const locale = lang === "fr" ? "fr-FR" : navigator.language.toLowerCase().startsWith("en") ? navigator.language : "en-GB";
  const hour12 =
    timeFormat === "auto"
      ? (new Intl.DateTimeFormat(locale, { hour: "numeric" }).resolvedOptions().hour12 ?? false)
      : timeFormat === "12h";
  const time = new Intl.DateTimeFormat(locale, { hour: hour12 ? "numeric" : "2-digit", minute: "2-digit", hour12 });
  const hour = hour12 ? new Intl.DateTimeFormat(locale, { hour: "numeric", hour12 }) : time;
  const weekday = new Intl.DateTimeFormat(locale, { weekday: "short" });
  const monthShort = new Intl.DateTimeFormat(locale, { month: "short" });
  const monthYear = new Intl.DateTimeFormat(locale, { month: "long", year: "numeric" });
  const monthShortYear = new Intl.DateTimeFormat(locale, { month: "short", year: "numeric" });
  const fullDate = new Intl.DateTimeFormat(locale, { weekday: "long", day: "numeric", month: "long" });
  const shortDate = new Intl.DateTimeFormat(locale, { weekday: "short", day: "numeric", month: "short" });

  return {
    locale,
    hour12,
    time: (d: Date) => time.format(d),
    hourLabel: (h: number) => hour.format(new Date(2000, 0, 1, h)),
    weekday: (d: Date) => weekday.format(d),
    /** Two-letter weekday for the mini calendar ("lu", "Mo"). */
    weekdayMini: (d: Date) => weekday.format(d).replace(".", "").slice(0, 2),
    monthYear: (d: Date) => monthYear.format(d),
    fullDate: (d: Date) => fullDate.format(d),
    shortDate: (d: Date) => shortDate.format(d),
    rangeTitle(start: Date, end: Date, short = false): string {
      const last = addDays(end, -1);
      if (start.getMonth() === last.getMonth()) return (short ? monthShortYear : monthYear).format(start);
      const year = start.getFullYear() === last.getFullYear() ? "" : ` ${start.getFullYear()}`;
      return `${monthShort.format(start)}${year} – ${monthShort.format(last)} ${last.getFullYear()}`;
    },
  };
}

export function utcOffsetLabel(d = new Date()): string {
  const offset = -d.getTimezoneOffset();
  const sign = offset >= 0 ? "+" : "-";
  const h = Math.floor(Math.abs(offset) / 60);
  const m = Math.abs(offset) % 60;
  return `UTC${sign}${h}${m ? `:${String(m).padStart(2, "0")}` : ""}`;
}
